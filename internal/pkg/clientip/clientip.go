// Package clientip — передача настоящего адреса клиента от гейтвея модулю
// через доверенный заголовок, тем же приёмом, что internal/pkg/authctx
// переносит личность пользователя: гейтвей стирает клиентское значение
// заголовка перед тем, как выставить своё (см. doc-комментарий handleProxy
// в gateway/server.go) — доверие держится на том, что NATS снаружи
// недостижим, клиент до модуля иначе, чем через гейтвей, не доберётся.
//
// Отдельный от authctx пакет, не ещё одно поле authctx.Claims: это не
// часть JWT-личности пользователя — адрес известен для любого запроса,
// авторизован вызывающий или нет, публичный метод или нет (в отличие от
// authctx.HeaderUserID и т.п., которые пусты для анонимного вызова).
package clientip

// Header — заголовок, которым гейтвей сообщает модулю адрес клиента (см.
// doc-комментарий пакета). Пустое значение на стороне модуля — запрос не
// прошёл через гейтвей (например, прямой вызов по NATS в тестах);
// вызывающему коду решать, как обращаться с пустым ключом.
const Header = "X-Client-Ip"
