// Команда builder выбирает модули, которые войдут в сборку, и генерирует
// cmd/bootstrap/imports.go с их blank-импортами.
//
//	go run ./cmd/builder                        # интерактивный выбор
//	go run ./cmd/builder -all                   # все модули
//	go run ./cmd/builder -modules identity,gateway
package main

import (
	"bufio"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"os/signal"
	"path/filepath"
	"slices"
	"strings"
	"syscall"
)

const (
	modulePath    = "dmatech.ru"
	cacheFileName = "dmatech_builder_choice.txt"
)

var (
	modulesDir  = filepath.Join("internal", "modules")
	importsPath = filepath.Join("cmd", "bootstrap", "imports.go")
)

type Module struct {
	Name     string
	Selected bool
}

func main() {
	all := flag.Bool("all", false, "включить все модули без интерактивного выбора")
	list := flag.String("modules", "", "список модулей через запятую без интерактивного выбора")
	flag.Parse()

	if err := run(*all, *list); err != nil {
		fmt.Fprintf(os.Stderr, "❌ %v\n", err)
		os.Exit(1)
	}
}

func run(all bool, list string) error {
	available, err := discoverModules(modulesDir)
	if err != nil {
		return err
	}
	if len(available) == 0 {
		return fmt.Errorf("не найдено ни одного модуля в %s", modulesDir)
	}

	var selected []string
	switch {
	case all:
		selected = available
	case list != "":
		if selected, err = parseModules(list, available); err != nil {
			return err
		}
	default:
		cachePath := filepath.Join(os.TempDir(), cacheFileName)
		var confirmed bool
		selected, confirmed, err = interactiveSelect(available, readCache(cachePath))
		if err != nil {
			return err
		}
		if !confirmed {
			fmt.Println("Выход без изменений.")
			return nil
		}
		if len(selected) == 0 {
			return errors.New("не выбрано ни одного модуля")
		}
		_ = os.WriteFile(cachePath, []byte(strings.Join(selected, ",")), 0o644)
	}

	if err := os.WriteFile(importsPath, renderImports(selected), 0o644); err != nil {
		return fmt.Errorf("не удалось записать %s: %w", importsPath, err)
	}
	fmt.Printf("✅ %s: %s\n", importsPath, strings.Join(selected, ", "))
	return nil
}

func discoverModules(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("ошибка чтения папки %s: %w", dir, err)
	}
	var names []string
	for _, entry := range entries {
		if entry.IsDir() {
			names = append(names, entry.Name())
		}
	}
	return names, nil
}

func parseModules(list string, available []string) ([]string, error) {
	var selected []string
	for _, name := range strings.Split(list, ",") {
		name = strings.TrimSpace(name)
		if name == "" || slices.Contains(selected, name) {
			continue
		}
		if !slices.Contains(available, name) {
			return nil, fmt.Errorf("неизвестный модуль %q (доступны: %s)", name, strings.Join(available, ", "))
		}
		selected = append(selected, name)
	}
	if len(selected) == 0 {
		return nil, errors.New("список модулей пуст")
	}
	slices.Sort(selected)
	return selected, nil
}

func renderImports(selected []string) []byte {
	var sb strings.Builder
	sb.WriteString("// Code generated by cmd/builder. DO NOT EDIT.\n\n")
	sb.WriteString("//go:build dynamic\n\n")
	sb.WriteString("package main\n\n")
	sb.WriteString("import (\n")
	for _, name := range selected {
		fmt.Fprintf(&sb, "\t_ %q\n", modulePath+"/internal/modules/"+name)
	}
	sb.WriteString(")\n")
	return []byte(sb.String())
}

func readCache(path string) map[string]bool {
	cached := make(map[string]bool)
	data, err := os.ReadFile(path)
	if err != nil {
		return cached
	}
	for _, name := range strings.Split(string(data), ",") {
		cached[strings.TrimSpace(name)] = true
	}
	return cached
}

// interactiveSelect рисует TUI-меню. Терминал настраивается через stty,
// у которого stdin направлен на /dev/tty: так работает и в Linux, и в macOS.
func interactiveSelect(names []string, cached map[string]bool) ([]string, bool, error) {
	tty, err := os.OpenFile("/dev/tty", os.O_RDWR, 0)
	if err != nil {
		return nil, false, fmt.Errorf("нет терминала для интерактивного выбора (используйте -all или -modules): %w", err)
	}
	defer tty.Close()

	stty := func(args ...string) ([]byte, error) {
		cmd := exec.Command("stty", args...)
		cmd.Stdin = tty
		return cmd.Output()
	}

	saved, err := stty("-g")
	if err != nil {
		return nil, false, fmt.Errorf("stty: %w", err)
	}
	restore := func() {
		_, _ = stty(strings.TrimSpace(string(saved)))
		fmt.Print("\033[?25h") // возвращаем курсор
	}
	if _, err := stty("cbreak", "-echo", "min", "1"); err != nil {
		return nil, false, fmt.Errorf("stty: %w", err)
	}
	defer restore()

	// Ctrl+C в cbreak-режиме приходит сигналом: восстанавливаем терминал перед выходом.
	sigs := make(chan os.Signal, 1)
	signal.Notify(sigs, os.Interrupt, syscall.SIGTERM)
	defer signal.Stop(sigs)
	go func() {
		if _, ok := <-sigs; ok {
			restore()
			fmt.Println()
			os.Exit(130)
		}
	}()

	modules := make([]Module, len(names))
	for i, name := range names {
		modules[i] = Module{Name: name, Selected: cached[name]}
	}

	cursor := 0
	reader := bufio.NewReader(tty)
	fmt.Print("\033[?25l") // прячем системный курсор

	for {
		draw(modules, cursor)

		b, err := reader.ReadByte()
		if err != nil {
			return nil, false, err
		}

		switch b {
		case 'q', 'Q':
			return nil, false, nil
		case 'w', 'W', 'k':
			cursor = max(cursor-1, 0)
		case 's', 'S', 'j':
			cursor = min(cursor+1, len(modules)-1)
		case ' ':
			modules[cursor].Selected = !modules[cursor].Selected
		case '\n', '\r':
			var selected []string
			for _, m := range modules {
				if m.Selected {
					selected = append(selected, m.Name)
				}
			}
			return selected, true, nil
		case 0x1b: // стрелки: ESC [ A/B или ESC O A/B
			b2, err := reader.ReadByte()
			if err != nil || (b2 != '[' && b2 != 'O') {
				continue
			}
			switch b3, _ := reader.ReadByte(); b3 {
			case 'A':
				cursor = max(cursor-1, 0)
			case 'B':
				cursor = min(cursor+1, len(modules)-1)
			}
		}
	}
}

func draw(modules []Module, cursor int) {
	var sb strings.Builder
	sb.WriteString("\033[H\033[2J") // полная очистка экрана
	sb.WriteString("=============================================\n")
	sb.WriteString(" 🚀 DMATECH - GO BUILDER CONFIG\n")
	sb.WriteString("=============================================\n")
	sb.WriteString(" [W/S или Стрелочки] - Навигация\n")
	sb.WriteString(" [Пробел] - Выбрать модуль  |  [Enter] - Подтвердить\n")
	sb.WriteString(" [Q] - Выход\n")
	sb.WriteString("---------------------------------------------\n")
	for i, mod := range modules {
		pointer := "   "
		if i == cursor {
			pointer = "👉 "
		}
		checkbox := "[ ]"
		if mod.Selected {
			checkbox = "[✅]"
		}
		fmt.Fprintf(&sb, "%s%s %s\n", pointer, checkbox, mod.Name)
	}
	sb.WriteString("---------------------------------------------\n")
	fmt.Print(sb.String())
}
